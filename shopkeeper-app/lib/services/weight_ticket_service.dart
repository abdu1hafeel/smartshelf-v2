import 'package:flutter/foundation.dart';
import 'package:supabase_flutter/supabase_flutter.dart';
import '../config/supabase_config.dart';
import '../models/verified_weight_ticket.dart';

class WeightTicketService {
  final SupabaseClient? _client;

  WeightTicketService({SupabaseClient? client})
      : _client = client ?? _tryResolveClient();

  static SupabaseClient? _tryResolveClient() {
    try {
      return SupabaseConfig.client;
    } catch (_) {
      return null;
    }
  }

  /// Fetches the latest valid (unconsumed & unexpired) verified weight ticket
  /// generated by an authorized ESP32 scale device for the specified shop and loose product.
  Future<VerifiedWeightTicket?> fetchLatestValidTicket({
    required String shopId,
    required String productId,
  }) async {
    final client = _client;
    if (client == null) return null;

    final nowIso = DateTime.now().toUtc().toIso8601String();

    try {
      final response = await client
          .from('verified_weight_tickets')
          .select('*, device:devices(name, device_identifier)')
          .eq('shop_id', shopId)
          .eq('product_id', productId)
          .eq('is_consumed', false)
          .gt('expires_at', nowIso)
          .order('created_at', ascending: false)
          .limit(1)
          .maybeSingle();

      if (response == null) {
        return null;
      }

      final ticket = VerifiedWeightTicket.fromJson(response);
      return ticket.isValidForCheckout ? ticket : null;
    } catch (err) {
      debugPrint('[WeightTicketService] Error fetching latest ticket: $err');
      return null;
    }
  }

  /// Subscribes to real-time verified weight ticket creation for a specific shop and product.
  /// Calls [onTicketReceived] whenever an authoritative valid ticket is issued.
  RealtimeChannel? subscribeToWeightTickets({
    required String shopId,
    required String productId,
    required void Function(VerifiedWeightTicket ticket) onTicketReceived,
    void Function(String status)? onStatusChange,
    void Function(Object error)? onError,
  }) {
    final client = _client;
    if (client == null) {
      onError?.call('Supabase client is not initialized.');
      return null;
    }

    // Scoped channel identifier matching tenant and product
    final channelName = 'weight_tickets_${shopId}_$productId';
    final channel = client.channel(channelName);

    channel
        .onPostgresChanges(
          event: PostgresChangeEvent.insert,
          schema: 'public',
          table: 'verified_weight_tickets',
          filter: PostgresChangeFilter(
            type: PostgresChangeFilterType.eq,
            column: 'product_id',
            value: productId,
          ),
          callback: (payload) async {
            try {
              final newRecord = payload.newRecord;

              // Tenant integrity guard
              if (newRecord['shop_id'] != shopId) return;

              // Disregard already consumed tickets
              if (newRecord['is_consumed'] == true) return;

              // Re-fetch authoritative ticket with joined device details
              final ticket = await fetchLatestValidTicket(
                shopId: shopId,
                productId: productId,
              );

              if (ticket != null && ticket.isValidForCheckout) {
                onTicketReceived(ticket);
              }
            } catch (err) {
              debugPrint('[WeightTicketService] Realtime payload processing error: $err');
              onError?.call(err);
            }
          },
        )
        .subscribe((status, [error]) {
          debugPrint('[WeightTicketService] Realtime subscription status: $status');
          switch (status) {
            case RealtimeSubscribeStatus.subscribed:
              onStatusChange?.call('CONNECTED');
              break;
            case RealtimeSubscribeStatus.channelError:
              onStatusChange?.call('ERROR');
              onError?.call(error ?? 'Realtime channel error');
              break;
            case RealtimeSubscribeStatus.timedOut:
              onStatusChange?.call('TIMEOUT');
              onError?.call('Realtime connection timed out');
              break;
            case RealtimeSubscribeStatus.closed:
              onStatusChange?.call('CLOSED');
              break;
          }
        });

    return channel;
  }

  /// Safely unsubscribes and removes a RealtimeChannel
  Future<void> unsubscribe(RealtimeChannel? channel) async {
    final client = _client;
    if (client != null && channel != null) {
      try {
        await client.removeChannel(channel);
      } catch (err) {
        debugPrint('[WeightTicketService] Error unsubscribing channel: $err');
      }
    }
  }
}
